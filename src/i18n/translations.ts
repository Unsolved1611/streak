export const translations: Record<Language, Record<TranslationKey, string>> = { en, es };

export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  const dict = translations[lang] ?? translations.en;
  let out = dict[key] ?? translations.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.split(`{${name}}`).join(String(value));
    }
  }
  return out;
}

